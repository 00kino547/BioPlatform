#!/bin/sh
set -e

mode=${TLS_MODE:-development}
send_hsts_on_dev=${SEND_HSTS_ON_DEV:-false}
dir=/etc/nginx/certs
self_cert=$dir/self-signed.pem
self_key=$dir/self-signed.key
cert=$dir/cert.pem
key=$dir/key.pem

have_openssl=0
if command -v openssl >/dev/null 2>&1; then
  have_openssl=1
fi

is_valid() {
  [ -f "$cert" ] && [ -f "$key" ] || return 1
  if [ "$have_openssl" = "1" ]; then
    openssl x509 -in "$cert" -noout -checkend 0 >/dev/null 2>&1 || return 1
    openssl x509 -in "$cert" -noout -pubkey >/dev/null 2>&1 || return 1
  fi
  return 0
}

remove_dev_certs() {
  rm -f "$self_cert" "$self_key"
  if [ -L "$cert" ]; then rm -f "$cert"; fi
  if [ -L "$key" ]; then rm -f "$key"; fi
}

case "$mode" in
  production)
    remove_dev_certs
    if ! is_valid; then
      echo "TLS_MODE=production requires a valid certificate/key pair." >&2
      echo "Place cert.pem and key.pem in ./certs/ (self-signed development certs are removed automatically)." >&2
      echo "Set TLS_MODE=development to auto-generate self-signed certs." >&2
      exit 1
    fi
    ;;
  *)
    remove_dev_certs
    if ! is_valid; then
      if [ "$have_openssl" = "0" ]; then
        echo "Installing openssl to generate a self-signed certificate..."
        apk add --no-cache openssl >/dev/null 2>&1 || exit 1
      fi
      echo "Generating self-signed certificate (development mode)..."
      openssl req -x509 -nodes -newkey rsa:2048 -days 3650 \
        -keyout "$self_key" -out "$self_cert" \
        -subj "/CN=localhost" \
        -addext "subjectAltName=DNS:localhost,IP:127.0.0.1"
      ln -sf self-signed.pem "$cert"
      ln -sf self-signed.key "$key"
      echo "Self-signed certificate generated: $self_cert (symlinked to cert.pem/key.pem)"
    fi
    ;;
esac

hsts_conf=/etc/nginx/conf.d/hsts.conf
if [ "$mode" = "production" ] || [ "$send_hsts_on_dev" = "true" ]; then
  printf 'add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;\n' > "$hsts_conf"
else
  printf '# HSTS disabled (development mode, SEND_HSTS_ON_DEV not true)\n' > "$hsts_conf"
fi

# Restore the real client IP from the standard X-Forwarded-For chain.
# This works with any reverse proxy in front (Cloudflare Tunnel, Nginx,
# Caddy, Traefik, HAProxy, ...) as long as it appends the client IP to
# X-Forwarded-For. Only trust sources the proxy connects from
# (docker bridge gateway + loopback), so direct clients cannot spoof it.
real_ip_conf=/etc/nginx/conf.d/real_ip.conf
trusted_ips=${CF_TRUSTED_IPS:-172.16.0.0/12,127.0.0.1,::1}
{
  for ip in $(printf '%s\n' "$trusted_ips" | tr ',' ' '); do
    [ -n "$ip" ] && printf 'set_real_ip_from %s;\n' "$ip"
  done
  printf 'real_ip_header X-Forwarded-For;\n'
  printf 'real_ip_recursive on;\n'
} > "$real_ip_conf"

# Custom-domain server blocks are generated and managed by the backend ACME
# service (certificates + nginx config in the shared certs volume). We only
# ensure the include file exists so nginx starts cleanly, and watch it for
# changes so the backend can drop certs/config and trigger a reload.
custom_conf=/etc/nginx/certs/custom-domains.conf
[ -f "$custom_conf" ] || printf '# Custom domain config is generated by the backend ACME service.\n' > "$custom_conf"

# Content-Security-Policy include file. The BACKEND generates it from
# config.yml (`public.ads`): only the configured ad networks' hosts, plus
# sha256 hashes for inline operator snippets (network: raw); with ads disabled
# the header carries zero ad hosts. Placeholder exists so first boot passes
# nginx -t even before the backend's first write.
csp_conf=/etc/nginx/certs/csp.conf
[ -f "$csp_conf" ] || printf '# CSP header is generated by the backend from config.yml (bioplatform cli csp).\n' > "$csp_conf"

# Watch the backend-managed custom-domains.conf and csp.conf and reload nginx
# when either one changes (new certificate issued, domain activated, ad config
# changed, etc.).
reload_watcher() {
  last=0
  last_csp=0
  while :; do
    dirty=0
    if [ -f "$custom_conf" ]; then
      now=$(stat -c %Y "$custom_conf" 2>/dev/null || printf '0')
      if [ "$now" != "$last" ]; then
        last=$now
        dirty=1
      fi
    fi
    if [ -f "$csp_conf" ]; then
      now_csp=$(stat -c %Y "$csp_conf" 2>/dev/null || printf '0')
      if [ "$now_csp" != "$last_csp" ]; then
        last_csp=$now_csp
        dirty=1
      fi
    fi
    if [ "$dirty" = "1" ]; then
      sleep 2
      if nginx -t >/dev/null 2>&1; then
        nginx -s reload >/dev/null 2>&1 || true
      else
        echo "nginx config test failed after reload trigger" >&2
      fi
    fi
    sleep 3
  done
}
reload_watcher &

# Map that tells nginx whether the request host is the app's own domain.
# Used to send social crawlers hitting the ROOT of a custom domain to the
# backend (server-rendered OG) while the app host keeps its static SPA OG.
app_host_conf=/etc/nginx/conf.d/app-host.conf
app_host=${APP_URL_HOST:-}
{
  printf '# App host map (generated at startup)\n'
  printf 'map $host $is_app_host {\n'
  printf '    default 0;\n'
  if [ -n "$app_host" ]; then
    printf '    %s 1;\n' "$app_host"
    case "$app_host" in
      www.*)
        printf '    %s 1;\n' "$(printf '%s' "$app_host" | cut -c5-)"
        ;;
      *)
        printf '    www.%s 1;\n' "$app_host"
        ;;
    esac
  fi
  printf '}\n'
} > "$app_host_conf"

# Optional Weblate virtual host. Weblate lives behind the opt-in `weblate`
# Compose profile. We generate a server block only when WEBLATE_SITE_DOMAIN is
# set AND the `weblate` service actually resolves on the Compose network, so an
# nginx-only stack never advertises a vhost whose upstream is missing (which
# would answer every translate request with a bare 502).
#
# Starting both profiles together races: the `weblate` container may not have
# registered its DNS name when nginx boots. We therefore wait briefly for the
# name to resolve. The wait is DNS-only (the container is on the network, not
# necessarily ready), bounded, and skipped when WEBLATE_SITE_DOMAIN is unset.
#
# If you start nginx first and Weblate long afterwards, restart nginx once the
# Weblate container is running so the vhost is generated.
#
# The upstream is a VARIABLE, for the same reason as the PocketBase proxy in
# site.conf: nginx resolves a literal host at config-load time, so a missing
# `weblate` container would otherwise stop nginx from starting at all. With a
# variable, a Weblate that disappears later is a 502 for that one host only.
#
# X-Forwarded-Proto is forced to `https`: the tunnel/nginx always terminate TLS
# in public, and Weblate (5.13+ / granian) needs that header to know the real
# scheme or it redirect-loops and rejects CSRF.
weblate_conf=/etc/nginx/conf.d/weblate.conf
weblate_domain=${WEBLATE_SITE_DOMAIN:-}
weblate_up=0
if [ -n "$weblate_domain" ]; then
  # Bounded wait (default 30s, override with WEBLATE_WAIT_SECONDS) so that
  # `--profile nginx --profile weblate up -d` still generates the vhost when
  # Weblate starts a moment after nginx.
  wait_seconds=${WEBLATE_WAIT_SECONDS:-30}
  waited=0
  while ! getent hosts weblate >/dev/null 2>&1; do
    if [ "$waited" -ge "$wait_seconds" ]; then
      break
    fi
    sleep 1
    waited=$((waited + 1))
  done
  if getent hosts weblate >/dev/null 2>&1; then
    weblate_up=1
  fi
fi
if [ "$weblate_up" = "1" ]; then
  cat > "$weblate_conf" <<EOF
# Generated from WEBLATE_SITE_DOMAIN at startup. Do not edit inside the container.
server {
    listen 80;
    listen [::]:80;
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $weblate_domain;

    ssl_certificate     /etc/nginx/certs/cert.pem;
    ssl_certificate_key /etc/nginx/certs/key.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 10m;

    include /etc/nginx/conf.d/hsts.conf;

    include /etc/nginx/conf.d/real_ip.conf;

    # Docker's embedded DNS, so the variable upstream resolves per request.
    resolver 127.0.0.11 valid=10s ipv6=off;

    location / {
        set \$weblate_upstream http://weblate:8080;
        proxy_pass \$weblate_upstream;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$xff_addr;
        proxy_set_header X-Forwarded-For \$xff_addr;
        proxy_set_header X-Forwarded-Host \$host;
        proxy_set_header X-Forwarded-Proto https;
        # Weblate 5 emits the obsolete interest-cohort=() policy. Modern
        # browsers report it as an unknown feature, and Weblate needs none of
        # the restricted capabilities, so remove the upstream header entirely.
        proxy_hide_header Permissions-Policy;
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        client_max_body_size 100M;
        proxy_cache_bypass \$http_upgrade;
    }
}
EOF
else
  # Two reasons to land here: no domain configured, or Weblate not running.
  # Both produce an inert file so the default app vhost keeps serving.
  printf '# Weblate vhost disabled (WEBLATE_SITE_DOMAIN unset or weblate service not running).\n' > "$weblate_conf"
fi

exec /docker-entrypoint.sh "$@"
